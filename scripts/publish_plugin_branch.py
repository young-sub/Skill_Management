"""Rebuild the install-only `plugin` branch from a source commit, without touching the working tree.

Hosts install from `young-sub/Skill_Management@plugin` (Codex) or `#plugin` (Claude Code). That branch holds
only what installation reads: both marketplace catalogs, `plugins/`, the `.gitattributes` lines that keep the
package inventory bytes, and a short README. The tree is written through a temporary index; a commit is made
only when the tree changed, on top of the current branch tip (fast-forward for clients).
"""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BRANCH = 'plugin'
PATHS = ('.agents', '.claude-plugin', 'plugins')
README = '''# agentic-coding marketplace

설치 전용 브랜치입니다. `main`의 marketplace 목록과 `plugins/`만 담습니다. 직접 수정하지 않고, `main`에서
`python scripts/publish_plugin_branch.py --push`로 다시 만듭니다. 소스와 문서는 `main` 브랜치에 있습니다.

```powershell
# Codex
codex plugin marketplace add young-sub/Skill_Management@plugin
codex plugin add agentic-coding@agentic-coding

# Claude Code
claude plugin marketplace add young-sub/Skill_Management#plugin
claude plugin install agentic-coding@agentic-coding
```
'''


def git(repo, *args, env=None, data=None):
    done = subprocess.run(['git', '-C', str(repo), *args], input=data, capture_output=True, check=False,
                          env=dict(os.environ, **(env or {})))
    if done.returncode:
        raise SystemExit(f"git {' '.join(args)} failed: {done.stderr.decode('utf-8', 'replace').strip()}")
    return done.stdout.decode('utf-8').strip()


def attributes(repo, source):
    lines = git(repo, 'show', f'{source}:.gitattributes').splitlines()
    kept = [line for line in lines if line.split(' ', 1)[0].startswith('plugins/')]
    return '# Preserve release bytes covered by package-files.json across clones.\n' + ''.join(f'{l}\n' for l in kept)


def blob(repo, text):
    return git(repo, 'hash-object', '-w', '--stdin', data=text.encode('utf-8'))


def publish(repo=ROOT, source='HEAD', branch=BRANCH, remote=None, push=False):
    source = git(repo, 'rev-parse', f'{source}^{{commit}}')
    if remote:
        subprocess.run(['git', '-C', str(repo), 'fetch', '-q', remote, f'+refs/heads/{branch}:refs/remotes/{remote}/{branch}'],
                       capture_output=True, check=False)  # absent on first publish
    tip_ref = f'refs/remotes/{remote}/{branch}' if remote else f'refs/heads/{branch}'
    tip = subprocess.run(['git', '-C', str(repo), 'rev-parse', '-q', '--verify', f'{tip_ref}^{{commit}}'],
                         capture_output=True, text=True).stdout.strip() or None
    entries = git(repo, 'ls-tree', '-r', '-z', source, '--', *PATHS)
    with tempfile.TemporaryDirectory() as temporary:
        env = {'GIT_INDEX_FILE': str(Path(temporary) / 'index')}
        git(repo, 'read-tree', '--empty', env=env)
        git(repo, 'update-index', '-z', '--index-info', env=env, data=entries.rstrip('\0').encode('utf-8') + b'\0')
        for name, text in (('README.md', README), ('.gitattributes', attributes(repo, source))):
            git(repo, 'update-index', '--add', '--cacheinfo', f'100644,{blob(repo, text)},{name}', env=env)
        tree = git(repo, 'write-tree', env=env)
    if tip and git(repo, 'rev-parse', f'{tip}^{{tree}}') == tree:
        commit, changed = tip, False
    else:
        message = f'Publish plugins from {source[:7]}\n\nGenerated by scripts/publish_plugin_branch.py.\n'
        commit = git(repo, 'commit-tree', tree, *(['-p', tip] if tip else []), '-m', message)
        changed = True
    git(repo, 'update-ref', f'refs/heads/{branch}', commit)
    if push and remote:
        git(repo, 'push', '-q', remote, f'refs/heads/{branch}:refs/heads/{branch}')
    return {'source': source, 'branch': branch, 'commit': commit, 'tree': tree, 'changed': changed}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', default='HEAD', help='commit whose catalogs and plugins/ are published')
    parser.add_argument('--remote', default='origin', help="remote whose branch tip is the parent ('' for local only)")
    parser.add_argument('--push', action='store_true', help='push the branch (fast-forward) to the remote')
    args = parser.parse_args(argv)
    result = publish(source=args.source, remote=args.remote or None, push=args.push)
    print(result)
    return 0


if __name__ == '__main__':
    sys.exit(main())
